package cmd

// `stone apply --template <dir>`: apply a folder of records to the current
// organization, matching them by natural key instead of by id.
//
// A workspace is one organization's records: every file carries the id of a
// record that exists in that organization, and apply writes new ids back. That
// makes it useless for the other job, which is onboarding many organizations
// from one folder, such as an application's contract (its Thing Types,
// operations and NATS role). A template is that folder:
//
//   - A file names its record by the spec's LookupKey (a thing type by `code`,
//     an operation or a role by `name`), never by id. A file holding `id`,
//     `updated`, `created` or `organization` is refused, because those belong
//     to one organization and a template belongs to none.
//   - A relation is written as the target's natural key (`operations:
//     [publish_door_decision, ...]`) and resolved in the current organization.
//   - A record that exists is PATCHed with the keys that differ; one that does
//     not is created. Nothing is written back to the files, so the same folder
//     applies to the next organization unchanged.
//   - Nothing is deleted, and records the template does not mention are left
//     alone. There is no optimistic lock: the template is the contract, and
//     applying it again is how an organization moves to a new version of it.
//
// Collections are applied in dependency order (an operation before the thing
// type naming it), one request per record. A template is tens of records, and
// one request each means a failure names its file and never leaves the commit
// of a batch unknown.

import (
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/stone-age-io/stone-cli/internal/ctx"
	"github.com/stone-age-io/stone-cli/internal/pb"
)

// templateRefused are the keys that tie a record to one organization.
var templateRefused = []string{"id", "updated", "created", "organization"}

// templateCollections are the definitions a template may hold: what every
// organization running an application needs the same. Not the instances. A
// thing's or a location's code is generated by the server, so a template has
// no key to find it by, and an identity, an invite or a Nebula host belongs to
// one organization by nature. TestTemplateCollectionsAreKeyed checks each is
// org-scoped, writable and keyed.
var templateCollections = map[string]bool{
	"location_types":        true,
	"thing_types":           true,
	"thing_type_operations": true,
	"nats_roles":            true,
}

func sortedSet(m map[string]bool) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// templateFile is one parsed template file.
type templateFile struct {
	Path       string
	Collection string
	Key        string // the LookupKey value
	Record     pb.Record
}

func (f templateFile) name() string {
	return f.Collection + "/" + filepath.Base(f.Path)
}

// readTemplate walks the template roots. Every file must sit in a directory
// named after one of templateCollections: a stray file in a
// contract is a mistake, not something to skip.
func readTemplate(roots []string) ([]templateFile, error) {
	var files []templateFile
	seen := map[string]string{}
	for _, root := range roots {
		abs, err := filepath.Abs(root)
		if err != nil {
			return nil, err
		}
		err = filepath.WalkDir(abs, func(path string, d fs.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if d.IsDir() {
				if path != abs && (strings.HasPrefix(d.Name(), ".") || d.Name() == jsDir) {
					return filepath.SkipDir
				}
				return nil
			}
			ext := strings.ToLower(filepath.Ext(path))
			if ext != ".yaml" && ext != ".yml" && ext != ".json" {
				return nil
			}
			coll := filepath.Base(filepath.Dir(path))
			spec, ok := specByCollection(coll)
			if !ok || !templateCollections[coll] {
				return fmt.Errorf("%s: %q is not a collection a template can hold (%s)", path, coll, strings.Join(sortedSet(templateCollections), ", "))
			}
			rec, err := pb.UnmarshalFile(path)
			if err != nil {
				return err
			}
			for _, k := range templateRefused {
				if _, has := rec[k]; has {
					return fmt.Errorf("%s: a template file has no %q; it names its record by %s and belongs to no organization", path, k, spec.LookupKey)
				}
			}
			key, _ := rec[spec.LookupKey].(string)
			if key == "" {
				return fmt.Errorf("%s: no %s, which is how a template finds its record", path, spec.LookupKey)
			}
			dup := coll + "\x00" + foldKey(spec.LookupKey, key)
			if prev, ok := seen[dup]; ok {
				return fmt.Errorf("%s and %s both declare %s %q", prev, path, spec.LookupKey, key)
			}
			seen[dup] = path
			files = append(files, templateFile{Path: path, Collection: coll, Key: key, Record: rec})
			return nil
		})
		if err != nil {
			return nil, err
		}
	}
	if len(files) == 0 {
		return nil, fmt.Errorf("no .yaml/.yml/.json files found under: %v", roots)
	}
	return files, nil
}

// foldKey is the form a key is compared in: a code ignores case (the
// platform's code indexes are COLLATE NOCASE, see keyFilter), a name does not.
func foldKey(key, v string) string {
	if key == "code" {
		return strings.ToLower(v)
	}
	return v
}

// templateOrder returns the template's collections so that each comes after
// every other template collection its relations point at, ties broken by
// entitySpecs order. A cycle is an error: neither side could be created first.
func templateOrder(files []templateFile) ([]string, error) {
	present := map[string]bool{}
	for _, f := range files {
		present[f.Collection] = true
	}
	var order []string
	done := map[string]bool{}
	for len(order) < len(present) {
		progressed := false
		for _, s := range entitySpecs {
			if !present[s.Collection] || done[s.Collection] {
				continue
			}
			ready := true
			for _, fl := range s.Fields {
				if fl.Target != "" && fl.Target != s.Collection && present[fl.Target] && !done[fl.Target] {
					ready = false
				}
			}
			if ready {
				order = append(order, s.Collection)
				done[s.Collection] = true
				progressed = true
			}
		}
		if !progressed {
			return nil, errors.New("the template's collections point at each other in a cycle")
		}
	}
	return order, nil
}

// templateOp is what applying one file comes to.
type templateOp struct {
	File  templateFile
	ID    string    // the existing record's id; empty means create
	Body  pb.Record // create: the whole record; update: the keys that differ
	Draft bool      // dry run only: a relation names a record this template would create
}

// planCollection compares one collection's template files with the server's
// records (already filtered to the current organization) and resolves their
// relations through lookup. pending holds, per collection, the keys this run
// would create but has not: only a dry run has any.
func planCollection(coll, org string, files []templateFile, server []pb.Record,
	lookup func(coll string) ([]pb.Record, error), pending map[string]map[string]bool) ([]templateOp, error) {
	spec, _ := specByCollection(coll)
	existing := map[string][]pb.Record{}
	for _, r := range server {
		v, _ := r[spec.LookupKey].(string)
		k := foldKey(spec.LookupKey, v)
		existing[k] = append(existing[k], r)
	}

	var ops []templateOp
	for _, f := range files {
		if f.Collection != coll {
			continue
		}
		local, err := yamlRoundTrip(f.Record)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", f.Path, err)
		}
		draft, err := resolveTemplateRelations(spec, f, local, lookup, pending)
		if err != nil {
			return nil, err
		}
		matches := existing[foldKey(spec.LookupKey, f.Key)]
		switch len(matches) {
		case 0:
			local["organization"] = org
			ops = append(ops, templateOp{File: f, Body: local, Draft: draft})
		case 1:
			remote, err := yamlRoundTrip(matches[0])
			if err != nil {
				return nil, fmt.Errorf("%s: %w", f.Path, err)
			}
			id, _ := matches[0]["id"].(string)
			patch := editPatch(remote, local)
			// The key is what matched. A code that matched in another case is
			// the organization's own spelling, and the template leaves it.
			delete(patch, spec.LookupKey)
			ops = append(ops, templateOp{File: f, ID: id, Body: patch, Draft: draft})
		default:
			return nil, fmt.Errorf("%s: %d %s in this organization have %s %q; a template needs it to name one",
				f.Path, len(matches), spec.Plural, spec.LookupKey, f.Key)
		}
	}
	return ops, nil
}

// resolveTemplateRelations replaces each relation's natural keys in local with
// ids, looked up in the current organization by the target's lookup keys. In a
// dry run a key the template would create resolves to a placeholder, and the
// op is marked a draft.
func resolveTemplateRelations(spec EntitySpec, f templateFile, local pb.Record,
	lookup func(coll string) ([]pb.Record, error), pending map[string]map[string]bool) (bool, error) {
	draft := false
	for _, fl := range spec.Fields {
		if fl.Target == "" || (fl.Type != FID && fl.Type != FIDs) {
			continue
		}
		raw, ok := local[fl.Name]
		if !ok || raw == nil {
			continue
		}
		var names []string
		switch v := raw.(type) {
		case string:
			if v != "" {
				names = []string{v}
			}
		case []any:
			for _, x := range v {
				s, ok := x.(string)
				if !ok {
					return false, fmt.Errorf("%s: %s holds %v; write the %s keys as strings", f.Path, fl.Name, x, fl.Target)
				}
				names = append(names, s)
			}
		default:
			return false, fmt.Errorf("%s: %s holds %v; write the %s key, or a list of them", f.Path, fl.Name, raw, fl.Target)
		}

		target, ok := specByCollection(fl.Target)
		if !ok {
			return false, fmt.Errorf("%s: %s points at %s, which this CLI does not model", f.Path, fl.Name, fl.Target)
		}
		records, err := lookup(fl.Target)
		if err != nil {
			return false, err
		}
		ids := make([]any, 0, len(names))
		for _, n := range names {
			id, err := matchTemplateKey(target, records, n)
			if err != nil {
				if pending[fl.Target][foldKey(target.LookupKey, n)] {
					ids = append(ids, "(new "+n+")")
					draft = true
					continue
				}
				return false, fmt.Errorf("%s: %s: %w", f.Path, fl.Name, err)
			}
			ids = append(ids, id)
		}
		if fl.Type == FID {
			if len(ids) == 0 {
				local[fl.Name] = ""
			} else if len(ids) > 1 {
				return false, fmt.Errorf("%s: %s takes one %s, got %d", f.Path, fl.Name, target.Name, len(ids))
			} else {
				local[fl.Name] = ids[0]
			}
		} else {
			local[fl.Name] = ids
		}
	}
	return draft, nil
}

// matchTemplateKey finds the one record whose lookup key is n, trying the
// spec's keys in order the way resolveRecordID does.
func matchTemplateKey(spec EntitySpec, records []pb.Record, n string) (string, error) {
	for _, key := range spec.lookupKeys() {
		var ids []string
		for _, r := range records {
			if v, _ := r[key].(string); v != "" && foldKey(key, v) == foldKey(key, n) {
				id, _ := r["id"].(string)
				ids = append(ids, id)
			}
		}
		switch len(ids) {
		case 0:
			continue
		case 1:
			return ids[0], nil
		default:
			return "", fmt.Errorf("%d %s are named %q in this organization (%s)", len(ids), spec.Plural, n, strings.Join(ids, ", "))
		}
	}
	return "", fmt.Errorf("no %s named %q in this organization", spec.Name, n)
}

// runApplyTemplate is `stone apply --template <dir>...`.
func runApplyTemplate(c ctx.Context, roots []string, dryRun, exitCode bool) error {
	if c.CurrentOrganization == "" {
		return errors.New("a template applies to the current organization, and none is set. run: stone org switch <org>")
	}
	if len(roots) == 0 {
		return errors.New("--template needs the template's directory, such as `stone apply --template contract/`")
	}
	files, err := readTemplate(roots)
	if err != nil {
		return err
	}
	order, err := templateOrder(files)
	if err != nil {
		return err
	}

	client := newPBClient(c)
	org := c.CurrentOrganization
	listings := map[string][]pb.Record{}
	lookup := func(coll string) ([]pb.Record, error) {
		if items, ok := listings[coll]; ok {
			return items, nil
		}
		items, err := client.ListAll(coll, pb.ListOptions{})
		if err != nil {
			return nil, fmt.Errorf("%s: %w", coll, err)
		}
		// The list rules already scope reads to the current organization;
		// filtering again costs nothing and keeps a superuser's listing from
		// matching another organization's record.
		mine := items[:0:0]
		for _, r := range items {
			if o, _ := r["organization"].(string); o == org {
				mine = append(mine, r)
			}
		}
		listings[coll] = mine
		return mine, nil
	}

	pending := map[string]map[string]bool{}
	var created, updated, unchanged, failed int
	for _, coll := range order {
		server, err := lookup(coll)
		if err != nil {
			return err
		}
		ops, err := planCollection(coll, org, files, server, lookup, pending)
		if err != nil {
			return err
		}
		spec, _ := specByCollection(coll)
		for _, op := range ops {
			switch {
			case op.ID == "" && dryRun:
				fmt.Printf("would create  %s\n", op.File.name())
				if pending[coll] == nil {
					pending[coll] = map[string]bool{}
				}
				pending[coll][foldKey(spec.LookupKey, op.File.Key)] = true
				created++
			case op.ID == "":
				rec, err := client.Create(coll, op.Body)
				if err != nil {
					fmt.Fprintf(os.Stderr, "failed   %s: %v\n", op.File.name(), err)
					failed++
					continue
				}
				id, _ := rec["id"].(string)
				fmt.Printf("created  %s -> %s\n", op.File.name(), id)
				created++
			case len(op.Body) == 0:
				unchanged++
			case dryRun:
				note := ""
				if op.Draft {
					note = ", naming records this template would create"
				}
				fmt.Printf("would update  %s (%s%s)\n", op.File.name(), strings.Join(sortedKeys(op.Body), ", "), note)
				updated++
			default:
				if _, err := client.Update(coll, op.ID, op.Body); err != nil {
					fmt.Fprintf(os.Stderr, "failed   %s: %v\n", op.File.name(), err)
					failed++
					continue
				}
				fmt.Printf("updated  %s (%s)\n", op.File.name(), strings.Join(sortedKeys(op.Body), ", "))
				updated++
			}
		}
		// The next collection may name what this one just created.
		delete(listings, coll)
		if failed > 0 {
			// Everything after this collection may point at what failed.
			later := order[indexOf(order, coll)+1:]
			if len(later) > 0 {
				fmt.Fprintf(os.Stderr, "stopped  before %s\n", strings.Join(later, ", "))
			}
			break
		}
	}

	if dryRun {
		fmt.Printf("dry run: would create %d  would update %d  unchanged %d\n", created, updated, unchanged)
	} else {
		fmt.Printf("created %d  updated %d  unchanged %d  failed %d\n", created, updated, unchanged, failed)
	}
	if failed > 0 {
		return fmt.Errorf("%d operation(s) failed", failed)
	}
	if dryRun && exitCode && created+updated > 0 {
		return errChangesPending
	}
	return nil
}

func indexOf(xs []string, x string) int {
	for i, v := range xs {
		if v == x {
			return i
		}
	}
	return -1
}
