#!/usr/bin/env bash
# Regenerate cmd/testdata/schema.json from a live platform server.
#
# cmd/schema_drift_test.go checks the CLI's field table against that file. It
# used to be a copy of the platform's schema.json, which has two faults: the copy
# was made by hand and went stale, and the file does not declare the fields
# pb-nats and pb-nebula add to their own collections at boot. So this script
# builds the platform, seeds a throwaway database, starts it, and asks it for
# every collection -- the schema a real deployment has, library fields included.
#
# Usage:  scripts/vendor-schema.sh [platform-checkout]   (default: ../platform)
#
# Point it at a clean checkout of a platform tag: the tag lands on the
# `platform release:` line release-notes.sh reads, and uncommitted platform work
# shows there as -dirty.
#
# Needs go, node and curl. Nothing outside a temp directory is touched except
# the two files under cmd/testdata. NATS does not need to run.
set -euo pipefail

cd "$(dirname "$0")/.."
PLATFORM="$(cd "${1:-../platform}" && pwd)"
OUT=cmd/testdata/schema.json
SOURCE=cmd/testdata/schema-source.txt

TMP="$(mktemp -d)"
PID=""
cleanup() {
  if [ -n "$PID" ]; then kill "$PID" 2>/dev/null || true; wait "$PID" 2>/dev/null || true; fi
  rm -rf "$TMP"
}
trap cleanup EXIT

BIN="$TMP/stone-age$(go env GOEXE)"
EMAIL=vendor@schema.test
export STONE_AGE_BOOTSTRAP_PASSWORD="vendor-$RANDOM$RANDOM$RANDOM"
PORT="$(node -e 'const s=require("net").createServer().listen(0,"127.0.0.1",()=>{console.log(s.address().port);s.close()})')"
URL="http://127.0.0.1:$PORT"

echo "==> build $PLATFORM"
(cd "$PLATFORM" && go build -o "$BIN" .)

echo "==> init and serve on $URL"
cd "$TMP"
"$BIN" init --dir "$TMP/pb_data" --nats-config "$TMP/nats.conf" \
  --email "$EMAIL" --operator-org Test >"$TMP/init.log" 2>&1 || { cat "$TMP/init.log"; exit 1; }
"$BIN" serve --dir "$TMP/pb_data" --http "127.0.0.1:$PORT" >"$TMP/serve.log" 2>&1 &
PID=$!
cd - >/dev/null

for _ in $(seq 60); do
  curl -sf "$URL/api/health" >/dev/null && break
  kill -0 "$PID" 2>/dev/null || { cat "$TMP/serve.log"; exit 1; }
  sleep 1
done

echo "==> fetch collections"
URL="$URL" EMAIL="$EMAIL" OUT="$OUT" node -e '
const { URL: base, EMAIL: identity, STONE_AGE_BOOTSTRAP_PASSWORD: password, OUT } = process.env;
(async () => {
  const auth = await fetch(base + "/api/collections/_superusers/auth-with-password", {
    method: "POST", headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ identity, password }),
  });
  if (!auth.ok) throw new Error("auth: " + auth.status + " " + await auth.text());
  const { token } = await auth.json();

  let items = [];
  for (let page = 1, total = 1; page <= total; page++) {
    const r = await fetch(base + "/api/collections?perPage=500&page=" + page, { headers: { Authorization: token } });
    if (!r.ok) throw new Error("collections: " + r.status + " " + await r.text());
    const body = await r.json();
    items = items.concat(body.items);
    total = body.totalPages;
  }
  // PocketBase internals (_superusers, _otps, ...) are not the platform schema.
  // Sorted, and without the timestamps of this throwaway database, so a refresh
  // diffs only what changed.
  items = items.filter(c => !c.system).sort((a, b) => a.name.localeCompare(b.name));
  for (const c of items) { delete c.created; delete c.updated; }
  require("fs").writeFileSync(OUT, JSON.stringify(items, null, 2) + "\n");
  console.log("wrote " + items.length + " collections to " + OUT);
})().catch(e => { console.error(e.message); process.exit(1); });
'

DESCRIBE="$(git -C "$PLATFORM" describe --tags --always --dirty)"
COMMIT="$(git -C "$PLATFORM" rev-parse --short HEAD)"
cat >"$SOURCE" <<EOF
The platform's collection schema, vendored so the CLI can check its own
field table against it. This file is DATA, not the source of truth -- the source
is the platform repo.

It is GENERATED by scripts/vendor-schema.sh from a live server: the script
builds the platform, seeds a throwaway database and lists every collection over
the API. That includes the fields pb-nats and pb-nebula add to their own
collections at boot, which the platform's schema.json does not declare.
PocketBase's own system collections are dropped. Do not edit it by hand.

platform release: $DESCRIBE
platform commit:  $COMMIT
generated:        $(date -u +%Y-%m-%d)

Refresh with:
  scripts/vendor-schema.sh [platform-checkout]
EOF
echo "==> wrote $SOURCE ($DESCRIBE)"
